/**
 * apps/api/src/product/sub_category/SubCategory.types.ts
 *
 * Source-verified types for the SubCategory module. Mirrors, field-for-field:
 *  - com.bloomscorp.loom.product.sub_category.orm.SubCategory          (extends BehemothORM, implements Cloneable)
 *  - com.bloomscorp.loom.product.sub_category.orm.SubCategoryPreview   (same physical table, projected fields)
 *  - com.bloomscorp.loom.product.sub_category.pojo.SubCategoryData
 *  - com.bloomscorp.loom.product.sub_category.pojo.FeaturedSubcategory
 *
 * ============================================================================
 * SCHEMA GAP — FLAGGED, NOT SILENTLY DROPPED
 * ============================================================================
 * The Java `SubCategory` entity declares two real, persisted columns that do
 * NOT exist on `sub_category` in the introspected schema
 * (`apps/api/src/database/schema/schema.ts`, generated by `pnpm db:introspect`
 * from the live DB):
 *
 *   - avgWorkHoursPerMeter (NUMERIC, nullable)
 *   - impactConfigVersion  (INTEGER, NOT NULL, default 1)
 *
 * This is independently corroborated by the Java side itself:
 * `SubCategoryData` (the native-query projection pojo) and
 * `SubCategoryNativeQuery.RETRIEVE_SUB_CATEGORY(_BY_ID)` both omit these two
 * columns from their SELECT list — so even the existing Java table-explorer
 * path never round-trips them either. Whatever migration added these two
 * Java-entity fields has evidently not been applied against `loom-local-db`
 * yet (or was rolled back).
 *
 * Decision: keep both fields on the API-facing types (so the `impactConfigVersion`
 * bump computation in SubCategory.service.ts can still be reasoned about and a
 * future migration slots in cleanly), but the repository/mapper CANNOT write
 * columns that don't exist — `SubCategory.repository.ts` does not reference
 * either field. Flagged again at the write site. A real DB migration adding
 * these two columns is required before this parity gap can close.
 *
 * `@anuprerna/types` is currently an empty workspace stub and the project has
 * no zod (or any validation library) dependency, so these are plain TS types
 * with hand-written runtime guards in SubCategory.dto.ts, exactly like
 * SkuGroup.types.ts / commerce/cart/types/cart.types.ts.
 */

/**
 * Generic file-upload representation for the three MultipartFile fields on
 * the Java entity (iconFile, socialImageFile, featuredImageFile). Kept local
 * and framework-agnostic rather than importing a multer type, since the
 * controller (which would own the actual multipart parsing) is out of scope
 * for this checkpoint.
 */
export interface UploadedFile {
  buffer: Buffer;
  originalName: string;
  mimeType: string;
}

