/**
 * Cross-module dependencies SubCategoryDAOController calls into — Segment
 * (already migrated per the checkpoint, but its TS module wasn't part of
 * this upload batch, so it's ported as a port exactly like Cart's
 * FabricPreviewPort/etc. rather than guessing an unverified import path/API
 * shape), the seven Profile modules (not yet migrated), and S3 storage.
 * Narrow ports typed exactly to the calls SubCategory actually makes. Wire
 * real providers in SubCategory.module.ts as each dependency becomes
 * available.
 */
export interface SegmentPort {
  retrieveSegment(id: number): Promise<{ id: number } | null>;
}

/**
 * All seven profile lookups (badge / made-to-order / volume-discount /
 * custom-size / size / finish / fabric) share an identical shape in source —
 * each DAOController exposes a single `retrieve<X>Profile(id)` accessor that
 * SubCategoryDAOController calls the same way. One generic port interface,
 * seven distinct injection tokens.
 */
export interface ProfileLookupPort {
  retrieveEntity(id: number): Promise<{ id: number } | null>;
}

/**
 * com.bloomscorp.loom.image.service.S3StorageManagerService — the two
 * methods SubCategoryDAOController actually calls. `uploadImage` is typed to
 * accept `null` deliberately: source calls
 * `s3Store.uploadImage(entity.getIconFile())` / `...FeaturedImageFile())`
 * unconditionally on create, even when the corresponding MultipartFile is
 * null (field defaults to `""`, not `null`, so the source's own
 * `!= null` guard around featuredImage never actually stops the call) — see
 * SubCategory.mapper.ts for where this quirk is preserved.
 */
export interface S3StoragePort {
  uploadImage(file: UploadedFile | null): Promise<string>;
  initiateDeleteImageTask(url: string): Promise<void>;
}

